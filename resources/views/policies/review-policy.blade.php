        <div class="policy-header">
            <h1 class="policy-title">Journal of Applied and Pure Research (JAPR)</h1>
            <p class="policy-subtitle">Comprehensive Review Policy</p>
            <p class="policy-version">Version 2.0 | Effective Date: {{ date('F d, Y') }}</p>
        </div>

        <div class="policy-section">
            <h2 class="section-title">1. Introduction and Purpose</h2>
            <p class="policy-content">
                The Journal of Applied and Pure Research (JAPR) is committed to maintaining the highest standards of academic integrity, quality, and ethical publishing practices. This comprehensive review policy outlines the principles, procedures, and expectations that govern the peer review process for all manuscript submissions to JAPR.
            </p>
            <p class="policy-content">
                By submitting a manuscript to JAPR, authors acknowledge their understanding and acceptance of this review policy and agree to comply with all specified requirements and procedures.
            </p>
        </div>

        <div class="policy-section">
            <h2 class="section-title">2. Peer Review Process Overview</h2>

            <h3 class="subsection-title">2.1 Editorial Review Structure</h3>
            <p class="policy-content">
                JAPR employs a rigorous multi-stage review process involving:
            </p>
            <ul class="policy-list">
                <li><strong>Editor-in-Chief:</strong> Provides strategic oversight and makes final publication decisions</li>
                <li><strong>Managing Editor:</strong> Oversees day-to-day operations and manuscript processing</li>
                <li><strong>Associate Editors:</strong> Manage the peer review process for assigned manuscripts</li>
                <li><strong>External Reviewers:</strong> Provide expert evaluation and recommendations</li>
                <li><strong>Desk Editors:</strong> Provide administrative and preliminary review support</li>
            </ul>

            <h3 class="subsection-title">2.2 Review Timeline</h3>
            <p class="policy-content">
                JAPR is committed to efficient and timely review processes:
            </p>
            <ul class="policy-list">
                <li>Initial editorial screening: 5-7 business days</li>
                <li>Peer review assignment: 3-5 business days</li>
                <li>Reviewer evaluation period: 21-28 days</li>
                <li>Editorial decision: 5-7 business days after receiving reviews</li>
                <li>Author revision period: 30-60 days (depending on revision scope)</li>
            </ul>
        </div>

        <div class="policy-section">
            <h2 class="section-title">3. Manuscript Submission Requirements</h2>

            <h3 class="subsection-title">3.1 Eligibility Criteria</h3>
            <p class="policy-content">
                Manuscripts submitted to JAPR must meet the following requirements:
            </p>
            <ul class="policy-list">
                <li>Original research that has not been published elsewhere</li>
                <li>Compliance with ethical standards in research and publication</li>
                <li>Appropriate scope and significance for the journal's mission</li>
                <li>Technical quality and methodological rigor</li>
                <li>Clear presentation and adherence to submission guidelines</li>
            </ul>

            <h3 class="subsection-title">3.2 Required Documentation</h3>
            <ul class="policy-list">
                <li>Complete manuscript in PDF format</li>
                <li>Cover letter with research significance statement</li>
                <li>Author contribution statements</li>
                <li>Conflict of interest declarations</li>
                <li>Ethical approval documentation (where applicable)</li>
                <li>Data availability statements</li>
                <li>Funding acknowledgments</li>
            </ul>
        </div>

        <div class="policy-section">
            <h2 class="section-title">4. Review Criteria and Standards</h2>

            <h3 class="subsection-title">4.1 Evaluation Parameters</h3>
            <p class="policy-content">
                All manuscripts are evaluated based on the following criteria:
            </p>
            <ul class="policy-list">
                <li><strong>Novelty and Significance:</strong> Original contribution to the field</li>
                <li><strong>Technical Quality:</strong> Methodological rigor and experimental design</li>
                <li><strong>Clarity and Presentation:</strong> Writing quality and organization</li>
                <li><strong>Literature Review:</strong> Comprehensive coverage of relevant work</li>
                <li><strong>Data Analysis:</strong> Appropriate statistical methods and interpretation</li>
                <li><strong>Conclusions:</strong> Supported by results and properly contextualized</li>
                <li><strong>Ethical Compliance:</strong> Adherence to research ethics standards</li>
            </ul>

            <h3 class="subsection-title">4.2 Review Recommendations</h3>
            <p class="policy-content">
                Reviewers may provide one of the following recommendations:
            </p>
            <ul class="policy-list">
                <li><strong>Accept:</strong> Manuscript meets publication standards with no required changes</li>
                <li><strong>Minor Revisions:</strong> Small improvements needed before acceptance</li>
                <li><strong>Major Revisions:</strong> Significant changes required with re-review</li>
                <li><strong>Reject:</strong> Manuscript does not meet publication standards</li>
            </ul>
        </div>

        <div class="policy-section">
            <h2 class="section-title">5. Author Responsibilities and Obligations</h2>

            <h3 class="subsection-title">5.1 Research Integrity</h3>
            <div class="highlight-box">
                <p><strong>Authors must ensure that their research adheres to the highest standards of integrity and ethical conduct.</strong></p>
            </div>
            <ul class="policy-list">
                <li>Reporting accurate and complete research findings</li>
                <li>Proper attribution of sources and acknowledgment of contributions</li>
                <li>Disclosure of potential conflicts of interest</li>
                <li>Compliance with institutional and international ethical guidelines</li>
                <li>Availability of data for verification when requested</li>
            </ul>

            <h3 class="subsection-title">5.2 Submission Ethics</h3>
            <ul class="policy-list">
                <li>Manuscripts must not be submitted to multiple journals simultaneously</li>
                <li>Previously published work must be clearly identified and properly cited</li>
                <li>All co-authors must approve the submission</li>
                <li>Authorship must reflect significant contributions to the research</li>
                <li>Any prior publication of preliminary results must be disclosed</li>
            </ul>

            <h3 class="subsection-title">5.3 Response to Reviews</h3>
            <ul class="policy-list">
                <li>Authors must provide detailed responses to reviewer comments</li>
                <li>Revisions should address all substantive concerns raised</li>
                <li>Disagreements with reviewers should be respectfully articulated</li>
                <li>Changes to the manuscript should be clearly identified</li>
                <li>Additional data or analyses may be required based on reviewer feedback</li>
            </ul>
        </div>

        <div class="policy-section">
            <h2 class="section-title">6. Reviewer Responsibilities and Guidelines</h2>

            <h3 class="subsection-title">6.1 Review Standards</h3>
            <p class="policy-content">
                Reviewers are expected to provide comprehensive, constructive, and timely evaluations that maintain the highest standards of scholarly review.
            </p>
            <ul class="policy-list">
                <li>Thorough assessment of scientific merit and methodology</li>
                <li>Constructive feedback for improvement</li>
                <li>Objective evaluation free from personal or institutional bias</li>
                <li>Confidential handling of manuscript content</li>
                <li>Timely completion of reviews within agreed timeframes</li>
            </ul>

            <h3 class="subsection-title">6.2 Conflict of Interest</h3>
            <ul class="policy-list">
                <li>Reviewers must disclose any potential conflicts of interest</li>
                <li>Close collaborators or competitors should decline review requests</li>
                <li>Financial or personal relationships with authors must be declared</li>
                <li>Institutional affiliations that may create bias should be considered</li>
            </ul>
        </div>

        <div class="policy-section">
            <h2 class="section-title">7. Editorial Decision Process</h2>

            <h3 class="subsection-title">7.1 Decision Authority</h3>
            <p class="policy-content">
                Editorial decisions are made hierarchically with appropriate oversight:
            </p>
            <ul class="policy-list">
                <li>Associate Editors manage the review process and make initial recommendations</li>
                <li>Managing Editors coordinate editorial operations and review decisions</li>
                <li>Editor-in-Chief makes final publication decisions</li>
                <li>Editorial board provides guidance on policy and standards</li>
            </ul>

            <h3 class="subsection-title">7.2 Decision Communications</h3>
            <ul class="policy-list">
                <li>Authors receive detailed feedback with editorial decisions</li>
                <li>Reviewer comments are provided (with anonymity maintained)</li>
                <li>Clear guidance is given for any required revisions</li>
                <li>Appeals process is available for disputed decisions</li>
            </ul>
        </div>

        <div class="policy-section">
            <h2 class="section-title">8. Quality Assurance and Continuous Improvement</h2>

            <h3 class="subsection-title">8.1 Review Quality Monitoring</h3>
            <ul class="policy-list">
                <li>Regular assessment of reviewer performance and feedback quality</li>
                <li>Editorial team training and development programs</li>
                <li>Systematic review of editorial decisions and outcomes</li>
                <li>Author and reviewer satisfaction surveys</li>
            </ul>

            <h3 class="subsection-title">8.2 Policy Updates</h3>
            <div class="important-note">
                <p><strong>Important:</strong> This review policy is subject to periodic updates to reflect best practices and evolving standards in academic publishing. Authors and reviewers will be notified of any significant changes.</p>
            </div>
        </div>

        <div class="policy-section">
            <h2 class="section-title">9. Data and Privacy Protection</h2>

            <h3 class="subsection-title">9.1 Manuscript Confidentiality</h3>
            <ul class="policy-list">
                <li>All submitted manuscripts are treated as confidential documents</li>
                <li>Content may not be shared outside the review process</li>
                <li>Editors and reviewers are bound by confidentiality agreements</li>
                <li>Secure systems are used for manuscript handling and storage</li>
            </ul>

            <h3 class="subsection-title">9.2 Author Data Protection</h3>
            <ul class="policy-list">
                <li>Personal information is collected only for publication purposes</li>
                <li>Data retention policies comply with international standards</li>
                <li>Authors may request access to their submitted data</li>
                <li>Data sharing agreements govern any external collaborations</li>
            </ul>
        </div>

        <div class="policy-section">
            <h2 class="section-title">10. Appeals and Dispute Resolution</h2>

            <h3 class="subsection-title">10.1 Appeal Process</h3>
            <p class="policy-content">
                Authors may appeal editorial decisions through a formal process:
            </p>
            <ul class="policy-list">
                <li>Appeals must be submitted within 30 days of the decision</li>
                <li>Detailed justification for the appeal must be provided</li>
                <li>Independent review by uninvolved editorial board members</li>
                <li>Final decisions are made by the Editor-in-Chief</li>
                <li>Appeal outcomes are communicated within 21 days</li>
            </ul>

            <h3 class="subsection-title">10.2 Ethical Concerns</h3>
            <ul class="policy-list">
                <li>Allegations of misconduct are investigated thoroughly</li>
                <li>Confidential reporting mechanisms are available</li>
                <li>Due process is followed for all parties involved</li>
                <li>Appropriate sanctions may be applied for confirmed violations</li>
            </ul>
        </div>

